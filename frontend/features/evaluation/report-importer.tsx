"use client";

import { useRef, useState } from "react";
import { z } from "zod";

const reportSchema = z.object({
  recall_at_k: z.number().min(0).max(1),
  precision_at_k: z.number().min(0).max(1),
  hit_rate_at_k: z.number().min(0).max(1),
  mrr: z.number().min(0).max(1),
  ndcg_at_k: z.number().min(0).max(1)
});
type EvaluationReport = z.infer<typeof reportSchema>;

const metrics: Array<{ key: keyof EvaluationReport; label: string; description: string }> = [
  { key: "recall_at_k", label: "Recall@K", description: "Relevant chunks found within the requested K." },
  { key: "precision_at_k", label: "Precision@K", description: "Retrieved chunks at K that were relevant." },
  { key: "hit_rate_at_k", label: "Hit rate@K", description: "Cases with at least one relevant chunk at K." },
  { key: "mrr", label: "MRR", description: "Rank quality of the first relevant chunk." },
  { key: "ndcg_at_k", label: "nDCG@K", description: "Position-aware ranking quality at K." }
];

export function EvaluationReportImporter() {
  const input = useRef<HTMLInputElement>(null);
  const [report, setReport] = useState<EvaluationReport>();
  const [filename, setFilename] = useState<string>();
  const [error, setError] = useState<string>();

  async function select(file: File | undefined) {
    setError(undefined); setReport(undefined); setFilename(undefined);
    if (!file) return;
    if (file.size > 1_048_576) { setError("Choose an evaluation JSON report smaller than 1 MB."); return; }
    try {
      const parsed = reportSchema.safeParse(JSON.parse(await file.text()));
      if (!parsed.success) { setError("This is not a supported evaluation report. Generate it with the documented backend score command."); return; }
      setReport(parsed.data); setFilename(file.name);
    } catch { setError("The selected file is not valid JSON."); }
  }

  return <section className="max-w-4xl space-y-6"><div><p className="text-sm font-medium text-accent">Evaluation</p><h1 className="mt-2 text-3xl font-semibold tracking-tight">Inspect a local evaluation report.</h1><p className="mt-3 text-muted">Import JSON generated by the backend evaluation CLI. This utility reads the file only in your browser and does not upload it.</p></div><div className="rounded-lg border border-line bg-panel p-5 shadow-panel"><input ref={input} className="sr-only" id="evaluation-report" type="file" accept="application/json,.json" onChange={(event) => void select(event.target.files?.[0])} /><button type="button" className="rounded border border-accent px-3 py-2 text-sm font-medium text-accent hover:bg-slate-50" onClick={() => input.current?.click()}>Choose evaluation JSON</button>{filename && <p className="mt-3 text-sm text-muted">Loaded locally: {filename}</p>}{error && <p className="mt-3 text-sm text-danger" role="alert">{error}</p>}</div>{report && <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">{metrics.map((metric) => <section key={metric.key} className="rounded-lg border border-line bg-panel p-5 shadow-panel"><p className="text-sm font-medium text-muted">{metric.label}</p><p className="mt-2 text-3xl font-semibold tabular-nums">{(report[metric.key] * 100).toFixed(1)}%</p><p className="mt-3 text-sm text-muted">{metric.description}</p></section>)}</div>}<section className="rounded-lg border border-line bg-panel p-5 text-sm text-muted"><h2 className="font-semibold text-ink">Generate a report</h2><code className="mt-3 block overflow-x-auto rounded bg-slate-50 p-3 text-xs">uv run python -m app.evaluation score --dataset dataset.jsonl --results results.jsonl --k 5 --output report.json</code><p className="mt-3">Evaluation run history, datasets, per-case failures, comparisons, and exports require evaluation HTTP APIs and are not available.</p></section></section>;
}
